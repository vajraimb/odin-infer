#!/usr/bin/env python3
"""Generate packages/qwen3_5/msl_tables.odin (MSL constant declarations for the
Metal codebook tables) from packages/ggml/tables.odin — the single source of
truth. Prevents the two copies from drifting.

Usage:
  python3 tools/gen_msl_tables.py          # regenerate + write
  python3 tools/gen_msl_tables.py --check  # fail if the committed file is stale
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "packages/ggml/tables.odin"
DST = ROOT / "packages/qwen3_5/msl_tables.odin"

TYPE_MAP = {"u8": "uchar", "u32": "uint", "u64": "ulong", "i8": "char"}

def parse(src: str):
    # strip // comments
    src = re.sub(r"//[^\n]*", "", src)
    pat = re.compile(r"(\w+)\s*:=\s*\[(\d+)\](u8|u32|u64|i8)\s*\{(.*?)\}", re.S)
    tables = []
    for m in pat.finditer(src):
        name, n, t, body = m.group(1), int(m.group(2)), m.group(3), m.group(4)
        vals = re.findall(r"-?\d+", body)
        assert len(vals) == n, f"{name}: expected {n} values, got {len(vals)}"
        tables.append((name, n, TYPE_MAP[t], vals))
    return tables

def render(tables):
    out = []
    out.append("// Generated by tools/gen_msl_tables.py from packages/ggml/tables.odin.")
    out.append("// Do not edit by hand — build.sh regenerates this file.")
    out.append("")
    out.append("package qwen3_5")
    out.append("")
    out.append("// Metal codebook tables. Values are the integer literals from")
    out.append("// tables.odin; the kernels read them byte-wise in little-endian order.")
    out.append("MSL_TABLES :: `// ---- quant codebook tables (generated from packages/ggml/tables.odin) ----")
    for name, n, msl_t, vals in tables:
        out.append(f"constant {msl_t} {name}[{n}] = {{")
        for i in range(0, n, 8):
            out.append("    " + ", ".join(vals[i:i+8]) + ",")
        out.append("};")
    out.append("`")
    out.append("")
    return "\n".join(out)

def main():
    tables = parse(SRC.read_text())
    assert len(tables) == 10, f"expected 10 tables, got {len(tables)}"
    text = render(tables)
    if "--check" in sys.argv:
        if DST.exists() and DST.read_text() == text:
            print(f"gen_msl_tables: OK ({len(tables)} tables, in sync)")
            return 0
        print(f"gen_msl_tables: STALE — {DST} differs from {SRC}; run tools/gen_msl_tables.py", file=sys.stderr)
        return 1
    DST.write_text(text)
    print(f"gen_msl_tables: wrote {len(tables)} tables to {DST}")

if __name__ == "__main__":
    sys.exit(main())
